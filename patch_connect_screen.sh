sed -i 's/import androidx.compose.material.icons.filled.Wifi/import androidx.compose.material.icons.filled.Wifi\nimport androidx.compose.material.icons.filled.Usb\nimport android.app.PendingIntent\nimport android.content.BroadcastReceiver\nimport android.content.Context\nimport android.content.Intent\nimport android.content.IntentFilter\nimport android.hardware.usb.UsbConstants\nimport android.hardware.usb.UsbDevice\nimport android.hardware.usb.UsbManager\nimport android.widget.Toast\nimport androidx.compose.runtime.DisposableEffect\nimport androidx.compose.ui.platform.LocalContext/g' /app/applet/app/src/main/java/com/yangyx/adbhelper/ui/screens/ConnectScreen.kt

awk '
/    var pairCode by remember { mutableStateOf/ {
    print
    print "    val context = LocalContext.current"
    print "    val ACTION_USB_PERMISSION = \"com.yangyx.adbhelper.USB_PERMISSION\""
    print ""
    print "    DisposableEffect(context) {"
    print "        val usbReceiver = object : BroadcastReceiver() {"
    print "            override fun onReceive(context: Context, intent: Intent) {"
    print "                if (ACTION_USB_PERMISSION == intent.action) {"
    print "                    synchronized(this) {"
