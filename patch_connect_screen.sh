    print "                                            endpointIn = ep"
    print "                                        } else if (ep.direction == UsbConstants.USB_DIR_OUT) {"
    print "                                            endpointOut = ep"
    print "                                        }"
    print "                                    }"
    print "                                    if (endpointIn != null && endpointOut != null) {"
    print "                                        val connection = usbManager.openDevice(device)"
    print "                                        if (connection != null) {"
    print "                                            connection.claimInterface(adbInterface, true)"
    print "                                            viewModel.connectUsb(connection, endpointIn, endpointOut)"
    print "                                            onNavigateToRemote()"
    print "                                        } else {"
    print "                                            Toast.makeText(context, \"无法打开 USB 设备\", Toast.LENGTH_SHORT).show()"
    print "                                        }"
    print "                                    }"
    print "                                } else {"
    print "                                    Toast.makeText(context, \"此设备不是支持 ADB 的设备\", Toast.LENGTH_SHORT).show()"
    print "                                }"
    print "                            }"
    print "                        } else {"
    print "                            Toast.makeText(context, \"用户拒绝了 USB 权限\", Toast.LENGTH_SHORT).show()"
    print "                        }"
    print "                    }"
    print "                }"
    print "            }"
    print "        }"
    print "        val filter = IntentFilter(ACTION_USB_PERMISSION)"
    print "        if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.TIRAMISU) {"
    print "            context.registerReceiver(usbReceiver, filter, Context.RECEIVER_NOT_EXPORTED)"
    print "        } else {"
    print "            context.registerReceiver(usbReceiver, filter)"
    print "        }"
    print "        onDispose {"
    print "            context.unregisterReceiver(usbReceiver)"
    print "        }"
    print "    }"
