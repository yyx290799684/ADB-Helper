    print "                        if (intent.getBooleanExtra(UsbManager.EXTRA_PERMISSION_GRANTED, false)) {"
    print "                            device?.apply {"
    print "                                val usbManager = context.getSystemService(Context.USB_SERVICE) as UsbManager"
    print "                                var adbInterface: android.hardware.usb.UsbInterface? = null"
    print "                                for (i in 0 until device.interfaceCount) {"
    print "                                    val intf = device.getInterface(i)"
    print "                                    if (intf.interfaceClass == UsbConstants.USB_CLASS_VENDOR_SPEC &&"
    print "                                        intf.interfaceSubclass == 0x42 &&"
    print "                                        intf.interfaceProtocol == 0x01) {"
    print "                                        adbInterface = intf"
    print "                                        break"
    print "                                    }"
    print "                                }"
    print "                                if (adbInterface != null) {"
    print "                                    var endpointIn: android.hardware.usb.UsbEndpoint? = null"
